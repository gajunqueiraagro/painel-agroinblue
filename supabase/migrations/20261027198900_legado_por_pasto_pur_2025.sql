DECLARE
  c_faz constant uuid := 'd3396cdd-7c95-4d41-bcc5-577c0563ce87';
  c_div constant uuid := '4377f738-a89b-4ac5-ae4b-a465c67afe2e';
  c_adm constant uuid := '7bd0b6ad-2527-4be1-af58-f2cc0c0edd8e';
  v_cli uuid; v_mes text; v_n int; v_txt text; v_div_cards int := 0; v_itens int := 0;
BEGIN
  PERFORM set_config('request.jwt.claims', '{"sub":"7bd0b6ad-2527-4be1-af58-f2cc0c0edd8e","role":"authenticated"}', true);
  SELECT cliente_id INTO v_cli FROM public.fazendas WHERE id = c_faz;

  -- 2.0 pre-condicoes
  IF NOT coalesce(public.is_admin_agroinblue(c_adm), false) THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01: usuario % nao e admin', c_adm; END IF;
  IF (SELECT count(*) FROM public.valor_rebanho_realizado_validado WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12' AND status = 'validado') <> 12
     OR (SELECT count(*) FROM public.valor_rebanho_fechamento WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12' AND status = 'fechado') <> 12 THEN
    RAISE EXCEPTION 'LEGADO-POR-PASTO-01: os 12 meses de 2025 tem de estar com realizado validado e P2 fechado'; END IF;
  IF (SELECT count(*) FROM lpp_csv) <> 1417 OR (SELECT count(DISTINCT (ano_mes, pasto_nome)) FROM lpp_csv) <> 933
     OR (SELECT count(*) FROM lpp_csv WHERE categoria_codigo IS NOT NULL) <> 1137 THEN
    RAISE EXCEPTION 'LEGADO-POR-PASTO-01: dados do CSV nao conferem (1417 linhas, 933 cards, 1137 itens)'; END IF;
  CREATE TEMP TABLE lpp_pasto ON COMMIT DROP AS
    SELECT DISTINCT c.pasto_nome,
           CASE WHEN c.pasto_nome = 'Divergencia do Campeiro' THEN c_div END AS pasto_id
      FROM lpp_csv c;
  UPDATE lpp_pasto l SET pasto_id = (SELECT p.id FROM public.pastos p WHERE p.fazenda_id = c_faz AND p.nome = l.pasto_nome)
   WHERE l.pasto_id IS NULL;
  SELECT string_agg(l.pasto_nome, ', ') INTO v_txt FROM lpp_pasto l
   WHERE l.pasto_nome <> 'Divergencia do Campeiro'
     AND (SELECT count(*) FROM public.pastos p WHERE p.fazenda_id = c_faz AND p.nome = l.pasto_nome) <> 1;
  IF v_txt IS NOT NULL THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01: pasto do CSV nao resolve para 1 pasto: %', v_txt; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pastos WHERE id = c_div AND fazenda_id = c_faz AND tipo_uso = 'divergencia') THEN
    RAISE EXCEPTION 'LEGADO-POR-PASTO-01: pasto Divergencia % nao e da fazenda', c_div; END IF;
  SELECT string_agg(DISTINCT c.categoria_codigo, ', ') INTO v_txt FROM lpp_csv c
   WHERE c.categoria_codigo IS NOT NULL AND (SELECT count(*) FROM public.categorias_rebanho r WHERE r.codigo = c.categoria_codigo) <> 1;
  IF v_txt IS NOT NULL THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01: categoria sem cadastro unico: %', v_txt; END IF;
  SELECT count(*) INTO v_n FROM (SELECT DISTINCT c.ano_mes, l.pasto_id FROM lpp_csv c JOIN lpp_pasto l USING (pasto_nome)
     WHERE l.pasto_id <> c_div) z
   WHERE NOT EXISTS (SELECT 1 FROM public.fechamento_pastos fp WHERE fp.fazenda_id = c_faz AND fp.ano_mes = z.ano_mes AND fp.pasto_id = z.pasto_id);
  IF v_n > 0 THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01: % cards do CSV nao existem no sistema', v_n; END IF;
  IF EXISTS (SELECT 1 FROM public.fechamento_pastos WHERE fazenda_id = c_faz AND pasto_id = c_div AND ano_mes BETWEEN '2025-01' AND '2025-12') THEN
    RAISE EXCEPTION 'LEGADO-POR-PASTO-01: ja existe card do pasto Divergencia em 2025'; END IF;

  -- 2.1 foto antes
  CREATE TEMP TABLE lpp_foto_itens ON COMMIT DROP AS
    SELECT fp.ano_mes, r.codigo, sum(i.quantidade)::bigint AS qtd, sum(i.quantidade * i.peso_medio_kg) AS kg
      FROM public.fechamento_pasto_itens i JOIN public.fechamento_pastos fp ON fp.id = i.fechamento_id
      JOIN public.categorias_rebanho r ON r.id = i.categoria_id
     WHERE fp.fazenda_id = c_faz AND fp.ano_mes BETWEEN '2025-01' AND '2025-12' GROUP BY 1, 2;
  CREATE TEMP TABLE lpp_foto_vrv ON COMMIT DROP AS
    SELECT ano_mes, valor_total, cabecas, peso_medio_kg FROM public.valor_rebanho_realizado_validado
     WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12';
  CREATE TEMP TABLE lpp_foto_vrf ON COMMIT DROP AS
    SELECT ano_mes, valor_total, peso_total_kg FROM public.valor_rebanho_fechamento
     WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12';
  CREATE TEMP TABLE lpp_foto_si ON COMMIT DROP AS
    SELECT categoria, quantidade, peso_medio_kg FROM public.saldos_iniciais WHERE fazenda_id = c_faz AND ano = 2026 AND mes = 1;
  CREATE TEMP TABLE lpp_foto_status ON COMMIT DROP AS
    SELECT id, status FROM public.fechamento_pastos WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12';
  CREATE TEMP TABLE lpp_foto_2026 ON COMMIT DROP AS
    SELECT (SELECT md5(coalesce(string_agg(i.id::text || i.quantidade || '|' || coalesce(i.peso_medio_kg::text, '') || '|' || i.peso_total, ',' ORDER BY i.id), ''))
              FROM public.fechamento_pasto_itens i JOIN public.fechamento_pastos fp ON fp.id = i.fechamento_id
             WHERE fp.fazenda_id = c_faz AND fp.ano_mes >= '2026-01') AS itens_md5,
           (SELECT count(*) || '/' || coalesce(sum(i.quantidade), 0) FROM public.fechamento_pasto_itens i JOIN public.fechamento_pastos fp ON fp.id = i.fechamento_id
             WHERE fp.fazenda_id = c_faz AND fp.ano_mes >= '2026-01') AS itens_qtd,
           (SELECT count(*) FROM public.valor_rebanho_realizado_validado WHERE fazenda_id = c_faz AND ano_mes >= '2026-01' AND status = 'validado') AS vrv_validados,
           (SELECT md5(coalesce(string_agg(ano_mes || status || valor_total, ',' ORDER BY ano_mes), '')) FROM public.valor_rebanho_realizado_validado
             WHERE fazenda_id = c_faz AND ano_mes >= '2026-01') AS vrv_md5,
           (SELECT md5(coalesce(string_agg(ano_mes || status || coalesce(valor_total::text, ''), ',' ORDER BY ano_mes), '')) FROM public.valor_rebanho_fechamento
             WHERE fazenda_id = c_faz AND ano_mes >= '2026-01') AS vrf_md5;

