  UPDATE public.pastos SET data_inicio = '2020-01-01' WHERE id = c_div AND data_inicio = '2026-02-01';

  -- 2.3 abre o P2 dos 12 meses
  UPDATE public.valor_rebanho_realizado_validado SET status = 'em_revisao_legado'
   WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12' AND status = 'validado';
  GET DIAGNOSTICS v_n = ROW_COUNT; IF v_n <> 12 THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01: realizado aberto em % meses (esperado 12)', v_n; END IF;
  UPDATE public.valor_rebanho_fechamento SET status = 'aberto'
   WHERE fazenda_id = c_faz AND ano_mes BETWEEN '2025-01' AND '2025-12' AND status = 'fechado';
  GET DIAGNOSTICS v_n = ROW_COUNT; IF v_n <> 12 THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01: P2 aberto em % meses (esperado 12)', v_n; END IF;

  -- 2.4 por mes
  FOR v_mes IN SELECT to_char(d, 'YYYY-MM') FROM generate_series('2025-01-01'::date, '2025-12-01'::date, '1 month') d LOOP
    DELETE FROM public.fechamento_pasto_itens i USING public.fechamento_pastos fp
     WHERE i.fechamento_id = fp.id AND fp.fazenda_id = c_faz AND fp.ano_mes = v_mes
       AND fp.pasto_id IN (SELECT pasto_id FROM lpp_pasto);
    UPDATE public.fechamento_pastos fp SET tipo_uso_mes = k.tipo_uso_mes, lote_mes = k.lote_mes, observacao_mes = k.observacao_mes
      FROM (SELECT DISTINCT c.ano_mes, l.pasto_id, c.tipo_uso_mes, c.lote_mes, c.observacao_mes
              FROM lpp_csv c JOIN lpp_pasto l USING (pasto_nome) WHERE c.ano_mes = v_mes) k
     WHERE fp.fazenda_id = c_faz AND fp.ano_mes = v_mes AND fp.pasto_id = k.pasto_id;
    IF EXISTS (SELECT 1 FROM lpp_csv WHERE ano_mes = v_mes AND pasto_nome = 'Divergencia do Campeiro' AND categoria_codigo IS NOT NULL) THEN
      INSERT INTO public.fechamento_pastos (pasto_id, fazenda_id, cliente_id, ano_mes, status, tipo_uso_mes, lote_mes, observacao_mes)
