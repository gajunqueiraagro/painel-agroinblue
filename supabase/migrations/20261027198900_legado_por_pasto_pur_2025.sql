        (SELECT md5(coalesce(string_agg(ano_mes || status || coalesce(valor_total::text, ''), ',' ORDER BY ano_mes), '')) FROM public.valor_rebanho_fechamento
          WHERE fazenda_id = c_faz AND ano_mes >= '2026-01'))::text) THEN
    RAISE EXCEPTION 'LEGADO-POR-PASTO-01 prova 2.8: assinatura de 2026 mudou'; END IF;
  SELECT string_agg(m, ', ') INTO v_txt FROM (SELECT to_char(d, 'YYYY-MM') m FROM generate_series('2025-01-01'::date, '2025-12-01'::date, '1 month') d) z
   WHERE public._fn_status_pilares_fechamento(c_faz, z.m) #>> '{p1_mapa_pastos,status}' IS DISTINCT FROM 'oficial';
  IF v_txt IS NOT NULL THEN RAISE EXCEPTION 'LEGADO-POR-PASTO-01 prova 2.8: P1 nao oficial em %', v_txt; END IF;

