  SELECT c_faz, v_cli, to_char(d, 'YYYY-MM'), 'p2_valor_rebanho',
         'LEGADO-POR-PASTO-01: redistribuicao do legado por pasto conforme planilha MR25-PUR; totais por categoria identicos', c_adm, now()
    FROM generate_series('2025-01-01'::date, '2025-12-01'::date, '1 month') d;
