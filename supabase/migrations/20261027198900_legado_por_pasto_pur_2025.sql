    RAISE EXCEPTION 'LEGADO-POR-PASTO-01 prova 2.8: saldos_iniciais 2026/1 mudaram'; END IF;
  IF (SELECT row(itens_md5, itens_qtd, vrv_validados, vrv_md5, vrf_md5)::text FROM lpp_foto_2026) IS DISTINCT FROM (SELECT row(
